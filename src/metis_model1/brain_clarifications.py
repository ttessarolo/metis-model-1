    def release_answer_claim(self, *, session_id: str, owner: str) -> bool:
        """Release one queued answer claim so the same pending question can be retried."""

        session_id = _validate_session_id(session_id)
        owner = _validate_turn_id(owner)
        with self._lock:
            stored = self._pending_by_session.get(session_id)
            if stored is None or stored.claimed_by != owner:
                return False
            stored.claimed_by = None
            return True

    def conversation(
        self,
        *,
        session_id: str,
        request_fingerprint: str,
        now: float | None = None,
    ) -> ConversationSummary:
        session_id = _validate_session_id(session_id)
        request_fingerprint = _fingerprint(request_fingerprint, name="request_fingerprint")
        clock = self._now(now)
        with self._lock:
            self._sweep_locked(clock)
            session = self._sessions.get(session_id)
            conversation = session.conversations.get(request_fingerprint) if session else None
            if conversation is None:
                _fail("CONVERSATION_UNKNOWN", 404, "conversation is unknown")
            assert conversation is not None
            return self._summary_locked(conversation)

    def server_context(
        self,
        *,
        session_id: str,
        request_fingerprint: str,
        now: float | None = None,
    ) -> dict[str, Any] | None:
        """Return all bounded decisions for this logical request, in process only.

        Public summaries deliberately omit internal catalog/value identities.
        The orchestrator still needs those identities to resume a dialogue that
        legitimately requires more than one question.  This method keeps that
        authority server-side and never serializes it directly on the wire.
        """

        session_id = _validate_session_id(session_id)
        request_fingerprint = _fingerprint(request_fingerprint, name="request_fingerprint")
        clock = self._now(now)
        with self._lock:
            self._sweep_locked(clock)
            session = self._sessions.get(session_id)
            conversation = session.conversations.get(request_fingerprint) if session else None
            if conversation is None:
                return None
            summary = self._summary_locked(conversation)
            return {
                "conversation": summary.payload(),
                "decisions": [
                    {
                        **decision.payload(),
                        "resolved_value": decision.answer.resolved_value,
                    }
                    for decision in conversation.decisions
                ],
            }

    def set_latest_proposal(
        self,
        *,
        session_id: str,
        request_fingerprint: str,
        proposal_ref: str,
        now: float | None = None,
    ) -> ConversationSummary:
        session_id = _validate_session_id(session_id)
        request_fingerprint = _fingerprint(request_fingerprint, name="request_fingerprint")
        proposal_ref = _opaque(proposal_ref, name="proposal_ref", max_bytes=MAX_PROPOSAL_REF_BYTES)
        clock = self._now(now)
        with self._lock:
            self._sweep_locked(clock)
            session = self._sessions.get(session_id)
            conversation = session.conversations.get(request_fingerprint) if session else None
            if conversation is None:
                _fail("CONVERSATION_UNKNOWN", 404, "conversation is unknown")
            assert conversation is not None
            conversation.latest_proposal_ref = proposal_ref
            conversation.last_activity = clock
            session.last_activity = clock
            return self._summary_locked(conversation)

    def drop_session(self, session_id: str, *, revocation_owner: str | None = None) -> int:
        session_id = _validate_session_id(session_id)
        if revocation_owner is not None:
            revocation_owner = _validate_turn_id(revocation_owner)
        with self._lock:
            removed = self._drop_session_locked(session_id)
            if revocation_owner is not None:
                self._revoked_sessions[session_id] = revocation_owner
            return removed

    def release_revocation_guard(self, session_id: str, *, owner: str) -> None:
        """Release the transient guard after the revoked session's worker exits."""

        session_id = _validate_session_id(session_id)
        owner = _validate_turn_id(owner)
        with self._lock:
            if self._revoked_sessions.get(session_id) == owner:
                self._revoked_sessions.pop(session_id, None)

    def discard_pending_for_turn(self, *, session_id: str, parent_turn_id: str) -> bool:
        """Rollback only a pending question that was hidden by turn cancellation.

        Previously accepted decisions remain in the volatile session.  The
        question key and only the assumptions introduced with this question
        are released, allowing a deliberate retry of the same logical request.
        """

        session_id = _validate_session_id(session_id)
        parent_turn_id = _validate_turn_id(parent_turn_id)
        with self._lock:
            stored = self._pending_by_session.get(session_id)
            if stored is None or stored.public.parent_turn_id != parent_turn_id:
                return False

            pending = stored.public
            self._pending_by_session.pop(session_id, None)
            self._pending_by_id.pop(pending.clarification_id, None)
            session = self._sessions.get(session_id)
            conversation = session.conversations.get(stored.conversation_key) if session else None
            if conversation is not None:
                conversation.used_question_keys.discard(pending.question_key)
                for assumption in stored.assumptions_added:
                    if assumption in conversation.assumptions:
                        conversation.assumptions.remove(assumption)
                if (
                    conversation.rounds_used == 0
                    and not conversation.decisions
                    and not conversation.assumptions
                    and not conversation.used_question_keys
                    and conversation.latest_proposal_ref is None
                ):
                    session.conversations.pop(stored.conversation_key, None)
            if session is not None and not session.conversations:
                self._sessions.pop(session_id, None)
            return True

    def sweep_expired(self, *, now: float | None = None) -> int:
        clock = self._now(now)
        with self._lock:
            return self._sweep_locked(clock)

    def metrics(self) -> dict[str, int]:
        with self._lock:
            return {
                "sessions": len(self._sessions),
                "conversations": sum(len(item.conversations) for item in self._sessions.values()),
                "pending": len(self._pending_by_id),
                "retired": len(self._retired),
                "decisions": sum(
                    len(conversation.decisions)
                    for session in self._sessions.values()
                    for conversation in session.conversations.values()
                ),
                "assumptions": sum(
                    len(conversation.assumptions)
                    for session in self._sessions.values()
                    for conversation in session.conversations.values()
                ),
            }

    def has_pending(self, session_id: str) -> bool:
        session_id = _validate_session_id(session_id)
        with self._lock:
            self._sweep_locked(self._now(None))
            return session_id in self._pending_by_session

    def touch_session(self, session_id: str, *, now: float | None = None) -> None:
        """Keep existing volatile memory aligned with an authenticated chat turn."""

        session_id = _validate_session_id(session_id)
        clock = self._now(now)
        with self._lock:
            self._sweep_locked(clock)
            if session_id in self._revoked_sessions:
                _fail("SESSION_REVOKED", 409, "session was revoked")
            session = self._sessions.get(session_id)
            if session is not None:
                session.last_activity = clock

    aggregate_metrics = metrics

    def clear(self) -> int:
        with self._lock:
            removed = (
                len(self._sessions)
                + len(self._pending_by_id)
                + len(self._retired)
                + len(self._revoked_sessions)
            )
            self._sessions.clear()
            self._pending_by_session.clear()
            self._pending_by_id.clear()
            self._retired.clear()
            self._revoked_sessions.clear()
            return removed
